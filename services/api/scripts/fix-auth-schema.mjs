// Post-processes the generated Better Auth schema to follow the project convention of
// storing timestamps as timestamptz. Run by `pnpm auth:generate`.
import { readFileSync, writeFileSync } from 'node:fs';

const path = new URL('../src/db/auth-schema.ts', import.meta.url);
const source = readFileSync(path, 'utf8');
const fixed = source.replace(/timestamp\(("[a-z_]+")\)/g, 'timestamp($1, { withTimezone: true })');
writeFileSync(
  path,
  `// Generated by \`pnpm auth:generate\` from src/auth/options.ts. Do not edit by hand.\n${fixed}`,
);
